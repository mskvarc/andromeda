//! The TLS stack's endpoints, the certificate material it was started with,
//! and HTTPS clients that trust it.

use reqwest::{Certificate, Client, ClientBuilder, Identity, Response, tls};
use rustls_pki_types::{CertificateDer, pem::PemObject};
use std::{env, fs, path::PathBuf, time::Duration};

/// The directory holding the stack's generated certificate material.
const MATERIAL_ENV: &str = "ANDROMEDA_TEST_TLS_MATERIAL";

/// How long any one request may take.
const REQUEST_TIMEOUT: Duration = Duration::from_secs(15);

/// One listener of the TLS stack.
#[derive(Clone, Copy, Debug)]
pub enum Endpoint {
    /// The native-TLS broker: TLS 1.2 floor, optional client certificates.
    Native,
    /// The native-TLS broker requiring TLS 1.3 and a client certificate.
    Mutual,
    /// The native-TLS broker whose certificate the suite rotates.
    Rotating,
    /// The native-TLS broker's TLS management listener.
    Management,
    /// The nginx terminator's TLS listener in front of the plaintext broker.
    Proxy,
    /// The nginx terminator's plaintext listener, which redirects to TLS.
    ProxyPlaintext,
}

impl Endpoint {
    /// The variable overriding this endpoint's base URL, and its default.
    const fn base_setting(self) -> (&'static str, &'static str) {
        match self {
            Endpoint::Native => ("ANDROMEDA_TEST_TLS_NATIVE_URL", "https://127.0.0.1:1156/ngsi-ld/v1/"),
            Endpoint::Mutual => ("ANDROMEDA_TEST_TLS_MUTUAL_URL", "https://127.0.0.1:1157/ngsi-ld/v1/"),
            Endpoint::Rotating => ("ANDROMEDA_TEST_TLS_ROTATING_URL", "https://127.0.0.1:1158/ngsi-ld/v1/"),
            Endpoint::Management => ("ANDROMEDA_TEST_TLS_MANAGEMENT_URL", "https://127.0.0.1:1186/"),
            Endpoint::Proxy => ("ANDROMEDA_TEST_TLS_PROXY_URL", "https://127.0.0.1:8443/ngsi-ld/v1/"),
            Endpoint::ProxyPlaintext => ("ANDROMEDA_TEST_TLS_PROXY_PLAINTEXT_URL", "http://127.0.0.1:8080/ngsi-ld/v1/"),
        }
    }

    /// The endpoint's base URL, ending in `/`.
    pub fn base(self) -> String {
        let (variable, default) = self.base_setting();
        let base = env::var(variable).unwrap_or_else(|_| default.to_owned());
        format!("{}/", base.trim_end_matches('/'))
    }

    /// The URL of `path`, relative to the endpoint's base.
    pub fn url(self, path: &str) -> String {
        format!("{}{}", self.base(), path.trim_start_matches('/'))
    }

    /// The endpoint's origin, `scheme://host:port`.
    pub fn origin(self) -> String {
        let base = url::Url::parse(&self.base()).expect("endpoint base is a URL");
        base.origin().ascii_serialization()
    }
}

/// A file of the stack's generated certificate material.
pub fn material(file: &str) -> PathBuf {
    PathBuf::from(env::var(MATERIAL_ENV).unwrap_or_else(|_| "docker/compose/test/tls/certs".to_owned())).join(file)
}

/// The bytes of one material file, with a hint at how it is generated.
pub fn material_bytes(file: &str) -> Vec<u8> {
    let path = material(file);
    fs::read(&path).unwrap_or_else(|error| panic!("read {} (generated by `cargo xtask itest --stack tls`): {error}", path.display()))
}

/// The DER of the certificate in a PEM material file.
pub fn certificate_der(file: &str) -> Vec<u8> {
    CertificateDer::from_pem_slice(&material_bytes(file))
        .expect("material file holds a PEM certificate")
        .to_vec()
}

/// A client builder trusting only `authority`, reporting each connection's
/// peer certificate.
pub fn trusting(authority: &str) -> ClientBuilder {
    let root = Certificate::from_pem(&material_bytes(authority)).expect("authority is a PEM certificate");
    Client::builder().tls_certs_only([root]).tls_info(true).timeout(REQUEST_TIMEOUT)
}

/// A client builder trusting the stack's server authority.
pub fn trusting_the_stack() -> ClientBuilder {
    trusting("ca.crt")
}

/// A client certificate a broker may be shown.
#[derive(Clone, Copy, Debug)]
pub enum ClientCertificate {
    /// Issued by the client authority the mutual-TLS brokers trust.
    Authorized,
    /// Self-signed, from an issuer no broker trusts.
    Stranger,
}

impl ClientCertificate {
    /// The material file stem of this certificate and its key.
    const fn stem(self) -> &'static str {
        match self {
            ClientCertificate::Authorized => "client",
            ClientCertificate::Stranger => "stranger",
        }
    }
}

/// A client trusting the stack and presenting `certificate`.
pub fn presenting(builder: ClientBuilder, certificate: ClientCertificate) -> Client {
    let stem = certificate.stem();
    let mut bundle = material_bytes(&format!("{stem}.crt"));
    bundle.extend(material_bytes(&format!("{stem}.key")));
    builder
        .identity(Identity::from_pem(&bundle).expect("client identity is PEM"))
        .build()
        .expect("client builds")
}

/// The leaf certificate the server presented on the connection `response` came over.
pub fn presented_leaf(response: &Response) -> Option<Vec<u8>> {
    response
        .extensions()
        .get::<tls::TlsInfo>()
        .and_then(tls::TlsInfo::peer_certificate)
        .map(<[u8]>::to_vec)
}
