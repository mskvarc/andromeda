-- 0053: Freeze and analyse the rebuilt temporal relations
-- ============================================================================
-- All five relations were bulk-loaded inside one transaction, so every tuple
-- carries a live xmin: without a freeze, the first anti-wraparound vacuum
-- rewrites the whole history hypertable at an arbitrary later moment. The
-- ANALYZE is equally load-bearing -- the rebuilt relations have no statistics
-- at all, and the first temporal query would otherwise plan against defaults.
--
-- VACUUM cannot run inside a transaction block, so this file is marked
-- non-transactional and holds exactly one statement. VACUUM accepts a relation
-- list, which is what keeps the whole freeze to that one statement instead of
-- five separate files.
--
-- The runbook carries the operator check that the chunk heaps were actually
-- reached: a VACUUM on a hypertable root is expected to reach its chunks, and
-- that expectation is worth confirming once per fleet.
-- ============================================================================

VACUUM (FREEZE, ANALYZE) attribute_history, scope_history, temporal_entities, temporal_attribute_streams, write_records;
