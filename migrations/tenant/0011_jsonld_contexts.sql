-- ============================================================================
-- 0011: JSON-LD Contexts
-- ============================================================================
-- Stores JSON-LD @context documents used by the broker for compaction and
-- expansion (spec clause 5.2.19, operations 5.13.x).
--
-- Three kinds of context, stored as codes of the migration-owned registry the
-- broker compiles in (`andromeda-postgresql-codes` `JsonldContextKindCode`),
-- append-only and never renumbered; the check pins the range:
--   1 Cached            -- fetched from a remote URL and stored locally; a
--                          cached context always carries the `url` it was
--                          fetched from, which `chk_jsonld_contexts_cached_has_url`
--                          states
--   2 Hosted            -- created via the API and served by the broker
--   3 ImplicitlyCreated -- generated by the broker during entity operations
--
-- The broker resolves @context references by looking up contexts in this
-- table. `url` carries a UNIQUE constraint for fast deduplication of cached
-- remote contexts.
--
-- `id` and `url` are identifiers compared for equality only, so both are
-- `COLLATE "C"`: byte-wise comparison keeps their btrees free of any locale.
-- Both are bounded at 1024 UTF-8 octets, the identifier bound
-- (`IDENTIFIER_BYTE_LIMIT` in `andromeda-ngsi-ld-lexicon`), because a btree
-- refuses an entry past 2704 bytes; a remote context URL longer than that is
-- simply not cached, which the durable cache already treats as non-fatal.
-- The two JSONB documents are `COMPRESSION lz4`; a context is written once and
-- read on every request that names it, and lz4 decompresses far faster than
-- pglz for the same width.
--
-- Column order is physical: the not-null fixed-width columns first in
-- descending alignment, then the nullable `expires_at`, then the varlena
-- columns.
-- ============================================================================

CREATE TABLE jsonld_contexts (
    -- Metadata required by spec
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_usage TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    number_of_hits BIGINT NOT NULL DEFAULT 0,

    -- Context kind (`JsonldContextKindCode`).
    kind SMALLINT NOT NULL,

    -- Cache invalidation timestamp (optional)
    expires_at TIMESTAMPTZ,

    -- Local identifier, e.g. "urn:ngsi-ld:Context:550e8400-e29b...".
    -- This is the primary identifier for API operations.
    id TEXT COMPRESSION lz4 COLLATE "C" NOT NULL,

    -- Original URL the context was fetched from.
    -- Nullable for Hosted or ImplicitlyCreated contexts without an origin.
    -- Unique constraint prevents double-caching the same URL.
    url TEXT COMPRESSION lz4 COLLATE "C",

    -- The actual JSON-LD @context payload
    payload JSONB COMPRESSION lz4 NOT NULL,

    -- Custom extra info, e.g. headers from the source
    extra_info JSONB COMPRESSION lz4,

    CONSTRAINT pk_jsonld_contexts PRIMARY KEY (id),
    CONSTRAINT uq_jsonld_contexts_url UNIQUE (url),
    CONSTRAINT chk_jsonld_contexts_kind CHECK (kind BETWEEN 1 AND 3),
    CONSTRAINT chk_jsonld_contexts_cached_has_url CHECK (kind <> 1 OR url IS NOT NULL),
    CONSTRAINT chk_jsonld_contexts_id_length CHECK (octet_length(id) <= 1024),
    CONSTRAINT chk_jsonld_contexts_url_length CHECK (octet_length(url) <= 1024)
);

-- Fast filtering by kind (List operation)
CREATE INDEX idx_jsonld_contexts_kind ON jsonld_contexts(kind);
