-- second key column carries attribute_name_id for the "distinct attribute
-- names per entity" path. Migration 0007 documents this redundancy in its
-- own header; 0017 added `idx_tea_entity` regardless and it has accumulated
-- write amplification without serving any read.
--
-- All other indexes on entities, temporal_entity_attributes, and
-- attribute_current are preserved: the entities indexes back q-filter,
-- georel, scope, type, idPattern and expiration paths in
-- `src/query/sql/entity.rs` and `src/repository/entity/repo.rs`; the
-- attribute_current typed-column indexes are scaffolding for the q-filter
-- rewrite that compiles predicates to typed columns instead of
-- `jsonb_path_query_first(payload, ...)` (see 0015 header), and that
-- rewrite is on the near-term roadmap.
-- ============================================================================

DROP INDEX IF EXISTS idx_tea_entity;
