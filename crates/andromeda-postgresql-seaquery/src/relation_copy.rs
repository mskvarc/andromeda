//! Copying every row of one relation into another of the same shape.
//!
//! sea-query has no `OVERRIDING SYSTEM VALUE` on an insert, which a verbatim
//! copy into a relation with a `GENERATED ALWAYS` identity needs, so the copy
//! is spelled here.

use crate::{
    command::{Command, rendering::RenderedCommand},
    identifier::{quoted_iden, quoted_table},
};
use sea_query::{DynIden, TableName};

/// How a copy treats an identity column the target generates.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CopiedIdentity {
    /// The target generates no value the copy supplies, or takes a supplied
    /// one as given (`GENERATED BY DEFAULT`).
    Supplied,
    /// The target refuses a supplied value unless the insert overrides the
    /// system value (`GENERATED ALWAYS`), which the copy does.
    OverridingSystemValue,
}

/// `INSERT INTO <target> (<columns>) [OVERRIDING SYSTEM VALUE] SELECT
/// <columns> FROM <source>`.
#[derive(Clone, Debug)]
pub struct RelationCopy {
    /// The relation read.
    source: TableName,
    /// The relation written.
    target: TableName,
    /// The columns copied, in the same order on both sides.
    columns: Vec<DynIden>,
    /// Whether an identity value is copied over the target's generation.
    identity: CopiedIdentity,
}

impl RelationCopy {
    /// Copy `columns` of every row of `source` into `target`.
    #[must_use]
    pub const fn new(source: TableName, target: TableName, columns: Vec<DynIden>, identity: CopiedIdentity) -> RelationCopy {
        RelationCopy {
            source,
            target,
            columns,
            identity,
        }
    }
}

impl RenderedCommand for RelationCopy {
    fn rendered(&self) -> String {
        let columns = self.columns.iter().map(quoted_iden).collect::<Vec<_>>().join(", ");
        let overriding = match self.identity {
            CopiedIdentity::Supplied => "",
            CopiedIdentity::OverridingSystemValue => " OVERRIDING SYSTEM VALUE",
        };
        format!(
            "INSERT INTO {} ({columns}){overriding} SELECT {columns} FROM {}",
            quoted_table(&self.target),
            quoted_table(&self.source)
        )
    }
}

impl Command for RelationCopy {}

#[cfg(test)]
mod tests {
    use crate::{
        command::rendering::RenderedCommand,
        relation_copy::{CopiedIdentity, RelationCopy},
    };
    use pretty_assertions::assert_eq;
    use sea_query::{Alias, IntoIden, TableName};

    fn copy(identity: CopiedIdentity) -> String {
        RelationCopy::new(
            TableName::from((Alias::new("snap_2"), Alias::new("entities"))),
            TableName::from((Alias::new("snap_3_stg"), Alias::new("entities"))),
            vec![Alias::new("entity_key").into_iden(), Alias::new("id").into_iden()],
            identity,
        )
        .rendered()
    }

    #[test]
    fn a_copy_names_the_same_columns_on_both_sides() {
        assert_eq!(
            copy(CopiedIdentity::Supplied),
            r#"INSERT INTO "snap_3_stg"."entities" ("entity_key", "id") SELECT "entity_key", "id" FROM "snap_2"."entities""#
        );
    }

    #[test]
    fn a_copy_into_a_generated_always_identity_overrides_the_system_value() {
        assert_eq!(
            copy(CopiedIdentity::OverridingSystemValue),
            r#"INSERT INTO "snap_3_stg"."entities" ("entity_key", "id") OVERRIDING SYSTEM VALUE SELECT "entity_key", "id" FROM "snap_2"."entities""#
        );
    }

    #[test]
    fn a_copy_takes_no_lock_and_casts_nothing() {
        let copy = copy(CopiedIdentity::OverridingSystemValue);
        assert!(!copy.contains("LOCK"), "{copy}");
        assert!(!copy.contains("FOR SHARE"), "{copy}");
        assert!(!copy.contains("::"), "{copy}");
    }
}
