//! Forwarding the creation of an EntityMap to registered context sources
//! (clauses 5.14.4.4 and 5.14.5.4).
//!
//! A registration that advertises `createEntityMapQueryEntity` (or the
//! temporal twin) answers the same query with an EntityMap of its own. The
//! caller folds each returned map into the local one: the registration maps to
//! the remote map's identifier in `linkedMaps`, and every entity the remote map
//! lists is attributed to the registration in `entityMap`.

use crate::{
    FederationService,
    cache::Cacheability,
    entity_read::mode_admitted,
    error::FederationError,
    forwarding_url::forwarding_url,
    operation::ForwardingOperation,
    outcome::{ForwardGetOutcome, ForwardReadOutcome},
    read_fan_out::{SourceAnswer, read_outcome},
    request::{CsrModeFilter, TriggeringRequest},
};
use andromeda_http_headers::ngsild_warning::NgsiLdWarning;
use andromeda_jsonld::context_spec::ContextSpec;
use andromeda_ngsi_ld_lexicon::uri::Uri;
use andromeda_ngsi_ld_model::{entity_map::EntityMap, registration::ContextSourceRegistration};
use andromeda_ngsi_ld_query::type_selection::grammar::TypeExprRaw;
use chrono::Utc;
use futures::{StreamExt, stream};
use tracing::warn;

/// Which `EntityMap` creation resource a forwarded request targets.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EntityMapQueryKind {
    /// `GET /entityMaps` over current entities (clause 5.14.4).
    Entities,
    /// `GET /temporal/entityMaps` over temporal entities (clause 5.14.5).
    TemporalEntities,
}

impl EntityMapQueryKind {
    /// The operation a registration has to advertise for this kind.
    const fn operation(self) -> ForwardingOperation {
        match self {
            EntityMapQueryKind::Entities => ForwardingOperation::CreateEntityMapQueryEntity,
            EntityMapQueryKind::TemporalEntities => ForwardingOperation::CreateEntityMapQueryTemporal,
        }
    }

    /// The resource path below the API base.
    const fn path(self) -> &'static [&'static str] {
        match self {
            EntityMapQueryKind::Entities => &["entityMaps"],
            EntityMapQueryKind::TemporalEntities => &["temporal", "entityMaps"],
        }
    }
}

/// Parameters for forwarding an `EntityMap` creation.
pub struct ForwardEntityMapRequest<'a> {
    /// Which creation resource is targeted.
    pub kind: EntityMapQueryKind,
    /// Compact entity type for CSR matching.
    pub entity_type_compact: Option<&'a TypeExprRaw>,
    /// Optional entity identifiers for CSR matching.
    pub entity_ids: Option<&'a [Uri]>,
    /// The query string forwarded to each source: the full query for a
    /// non-split query, the entity selectors alone when split entities apply
    /// (clause 5.14.4.4 strips the filters before forwarding).
    pub query_string: &'a str,
    /// The JSON-LD context the triggering request resolved to.
    pub context: &'a ContextSpec,
    /// The request that triggered this forwarding.
    pub triggering: TriggeringRequest<'a>,
}

/// The `EntityMap` one registration's context source created for the query.
pub struct ForwardedEntityMap {
    /// The contributing registration.
    pub registration_id: Uri,
    /// The map the source created, absent when the attempt failed.
    pub map: Option<EntityMap>,
    /// Protocol warnings generated by the attempt.
    pub warnings: Vec<NgsiLdWarning>,
}

impl FederationService {
    /// Ask every matching context source that advertises `EntityMap` creation
    /// for its map of the same query.
    ///
    /// # Errors
    ///
    /// Returns [`FederationError::JsonLd`] when the requested entity type
    /// cannot be expanded against the request's context, and
    /// [`FederationError::Registration`] when the matching registrations
    /// cannot be read. A source that fails to answer does not fail the
    /// call: its attempt is reported as a [`ForwardedEntityMap`] without a
    /// map, except for the one case Table 6.34.3.1-1 relays, which the
    /// returned [`ForwardReadOutcome`] carries on its `sources`.
    pub async fn forward_entity_map_query(&self, request: ForwardEntityMapRequest<'_>) -> Result<ForwardReadOutcome<ForwardedEntityMap>, FederationError> {
        let ForwardEntityMapRequest {
            kind,
            entity_type_compact,
            entity_ids,
            query_string,
            context,
            triggering,
        } = request;
        if self.is_loop_detected(triggering.via) {
            return Ok(ForwardReadOutcome::empty());
        }
        let prepared_context = self.engine.prepare_term_context(context);
        let expanded_type = if let Some(t) = entity_type_compact.and_then(TypeExprRaw::as_single_type) {
            Some(self.engine.expand_type(t.as_str(), &prepared_context).await?)
        } else {
            None
        };
        let first_id = entity_ids.and_then(|ids| ids.first());
        let operation = kind.operation();
        let registrations: Vec<_> = self
            .csr_repo
            .find_matching(expanded_type.as_ref(), first_id)
            .await?
            .into_iter()
            .filter(|csr| operation.matches(csr))
            // Per spec 4.3.6.2: auxiliary CSRs only supplement existing data.
            .filter(|csr| mode_admitted(csr, CsrModeFilter::ExcludeAuxiliary))
            .collect();
        if registrations.is_empty() {
            return Ok(ForwardReadOutcome::empty());
        }
        let matched = registrations.len();
        let answers = stream::iter(registrations)
            .map(|registration| async move {
                let url = forwarding_url(registration.access.endpoint.url(), kind.path(), query_string);
                // Clause 6.3.17 allows caching for `/entities` only.
                let outcome = self.forward_get(&registration, url, context, triggering, Cacheability::Uncacheable, None).await;
                let error_status = outcome.error_status();
                let (map, warnings) = match outcome {
                    ForwardGetOutcome::Success(response) => match serde_json::from_value::<EntityMap>(response.body) {
                        Ok(map) => (Some(map), response.warnings),
                        Err(error) => {
                            warn!("Context source {} returned an invalid EntityMap: {}", registration.id, error);
                            let mut warnings = response.warnings;
                            warnings.push(NgsiLdWarning::RevalidationFailed(format!(
                                "Context source {} returned an invalid EntityMap: {error}",
                                registration.id
                            )));
                            (None, warnings)
                        }
                    },
                    // A source that declines to create a map is not abnormal (clause 5.5.14).
                    ForwardGetOutcome::NotFound(_) => (None, Vec::new()),
                    other @ (ForwardGetOutcome::InvalidPayload(_)
                    | ForwardGetOutcome::ErrorStatus(_)
                    | ForwardGetOutcome::Transport(_)
                    | ForwardGetOutcome::LoopDetected) => (None, other.warning(&registration.id).into_iter().collect()),
                };
                SourceAnswer {
                    mode: registration.access.mode.unwrap_or_default(),
                    error_status,
                    entry: Some(ForwardedEntityMap {
                        registration_id: registration.id,
                        map,
                        warnings,
                    }),
                }
            })
            .buffer_unordered(self.csr_concurrency)
            .collect()
            .await;
        Ok(read_outcome(answers, matched))
    }

    /// The registrations a request that references a live `EntityMap` contacts:
    /// the map's sources, looked up by identifier, in place of clause 5.12
    /// matching (clause 5.5.14, clause 5.12 last paragraph).
    pub(crate) async fn registrations_of_map(&self, map: &EntityMap) -> Result<Vec<ContextSourceRegistration>, FederationError> {
        let mut registrations = Vec::new();
        for registration_id in map.registrations() {
            if let Some(registration) = self.csr_repo.get(registration_id).await? {
                let expired = registration.lifecycle.expires_at.is_some_and(|expires_at| expires_at <= Utc::now());
                if !expired {
                    registrations.push(registration);
                }
            }
        }
        Ok(registrations)
    }
}
