//! The persisted kind of one stored JSON-LD context.

use crate::{compact_code_domain::CompactCodeDomain, compact_code_registry, registry::UnknownCompactCode};

compact_code_registry! {
    /// The kind of a stored `@context` document (clause 5.2.19).
    ///
    /// The labels are the specification's own `kind` tokens, which is the spelling
    /// a context's metadata carries on the wire.
    JsonldContextKindCode {
        frozen_at: (1, 0, 0),
        frozen_prefix: 3,
        frozen_digest: 0x53d0_5426_f333_273c,
        codes: {
            /// Fetched from a remote URL and stored locally.
            Cached = 1, "Cached";
            /// Created through the API and served by the broker.
            Hosted = 2, "Hosted";
            /// Generated by the broker during an entity operation.
            ImplicitlyCreated = 3, "ImplicitlyCreated";
        }
    }
}

#[cfg(test)]
mod tests {
    use crate::jsonld_context_kind::JsonldContextKindCode;
    use pretty_assertions::assert_eq;

    #[test]
    fn the_members_are_numbered_as_the_migration_documents_them() {
        assert_eq!(JsonldContextKindCode::ALL.len(), 3);
        assert_eq!(JsonldContextKindCode::Cached.code(), 1);
        assert_eq!(JsonldContextKindCode::ImplicitlyCreated.code(), 3);
    }

    #[test]
    fn zero_and_the_number_after_the_last_member_fail_to_decode() {
        assert!(JsonldContextKindCode::try_from(0).is_err());
        assert!(JsonldContextKindCode::try_from(4).is_err());
    }
}
