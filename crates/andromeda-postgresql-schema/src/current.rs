//! The relations that hold current entity state.
//!
//! The `entities` row and the `current_attribute_values` projection of its
//! attributes are the current-state grain a context statement and a temporal
//! statement both read, together with the `e` alias they read it under.

use sea_query::Iden;

/// The `entities` table - the identity and lifecycle of one current Entity.
///
/// The three relations `entities`, `entity_documents` and `entity_search`
/// together hold one Entity's current state, split by write pattern: identity
/// and expiry here, the payload and its version token in `entity_documents`,
/// the indexed query axes in `entity_search`. All three share `entity_key`.
#[derive(Iden, Clone, Copy)]
pub enum Entities {
    /// Table name: `entities`
    Table,
    /// Surrogate primary key every owned child relation references
    EntityKey,
    /// Entity URN identifier, the external identity of the row
    Id,
    /// Instant the entity was created (clause 4.8 `createdAt`).
    CreatedAt,
    /// Instant the entity expires, when it has one (clause 4.22 `expiresAt`).
    ExpiresAt,
    /// Earliest `expiresAt` any attribute instance of the payload carries, when
    /// one does (clause 4.22); what the attribute-expiry sweep ranges over.
    MinAttributeExpiresAt,
}

/// The `entity_documents` table - the expanded payload of one current Entity
/// and the version token that moves with it.
///
/// Carries no index other than its primary key so that every payload write
/// stays a heap-only-tuple update.
#[derive(Iden, Clone, Copy)]
pub enum EntityDocuments {
    /// Table name: `entity_documents`
    Table,
    /// Foreign key to `entities`, cascading on entity deletion; also the primary key
    EntityKey,
    /// Instant the payload was last written (clause 4.8 `modifiedAt`), the
    /// compare-and-set token an optimistic overwrite states
    ModifiedAt,
    /// Full expanded JSON-LD payload
    Payload,
}

/// The `entity_search` table - the indexed query axes of one current Entity.
///
/// Every index the planner uses to find entities is on this relation; the
/// write path rewrites its row only when one of these columns changed.
#[derive(Iden, Clone, Copy)]
pub enum EntitySearch {
    /// Table name: `entity_search`
    Table,
    /// Foreign key to `entities`, cascading on entity deletion; also the primary key
    EntityKey,
    /// The `xid8` of the transaction that last wrote the row
    WrittenXid,
    /// The clause 4.22 `expiresAt` of the hoisted default `location` instance,
    /// NULL when it carries none
    LocationExpiresAt,
    /// Array of `entity_type_names` keys, one per type the entity carries
    EntityTypeNameKeys,
    /// Array of `attribute_names` keys, one per attribute the payload carries
    /// (clause 5.5.9 `attrs`)
    AttributeNameKeys,
    /// Array of `attribute_names` keys, one per attribute instance the payload
    /// carries (clause 4.5.5), aligned with `attribute_instance_kinds`
    AttributeInstanceNameKeys,
    /// Array of attribute family codes, one per attribute instance, aligned
    /// with `attribute_instance_name_keys`
    AttributeInstanceKinds,
    /// Array of `ltree` scope paths an entity currently belongs to (clause 4.18).
    ScopePaths,
    /// The default `GeoProperty` geometry (clause 4.10).
    Location,
    /// The `geography` projection of `location`, generated by the database
    LocationGeography,
    /// The `observationSpace` geometry (clause 4.5.4).
    ObservationSpace,
    /// The `operationSpace` geometry (clause 4.5.4).
    OperationSpace,
}

/// The `entity_type_members` table - one row per type one current Entity
/// carries (clause 4.17), keyed by type and then identifier.
///
/// A type selection walks one key range of it in identifier order, so a page
/// of a type reads the rows it skips and keeps and no Entity of another type.
#[derive(Iden, Clone, Copy)]
pub enum EntityTypeMembers {
    /// Table name: `entity_type_members`
    Table,
    /// Foreign key to `entities`, cascading on entity deletion
    EntityKey,
    /// The `entity_type_names` key of the type carried
    EntityTypeNameKey,
    /// The Entity's identifier, copied from `entities` so the walk is ordered by it
    Id,
}

/// The `current_attribute_values` table - one row per current attribute
/// instance of an entity.
///
/// The grain is the clause 4.5.5 dataset grain: an entity, an attribute name
/// and an optional `datasetId`. Exactly one of the eight typed value columns is
/// populated on any row, and which one is pinned to `value_kind`, so a
/// predicate that knows the value shape it is comparing knows the column it has
/// to read. A String is the one shape with two columns, and its byte length
/// alone picks between them
/// ([`ProjectedStringColumn`](crate::projected_string_column::ProjectedStringColumn)).
///
/// A deleted attribute is an absent row rather than a stored marker: the
/// tombstone value kind belongs to history and never appears here, which is why
/// row presence alone answers an existence test.
#[derive(Iden, Clone, Copy)]
pub enum CurrentAttributeValues {
    /// Table name: `current_attribute_values`
    Table,
    /// Foreign key to `entities`, cascading on entity deletion
    EntityKey,
    /// Foreign key to `attribute_names`
    AttributeNameKey,
    /// Attribute family code of the projected instance
    AttributeKind,
    /// Value shape code, pinning which typed value column is populated
    ValueKind,
    /// `DateTime` value, when `value_kind` selects it
    ValueDateTime,
    /// The instance's own clause 4.22 `expiresAt`, NULL when it never expires
    ExpiresAt,
    /// Foreign key to `unit_codes` for the instance's `unitCode` (clause 4.5.2)
    UnitCodeId,
    /// Boolean value, when `value_kind` selects it
    ValueBoolean,
    /// Optional dataset identifier (clause 4.5.5)
    DatasetId,
    /// Numeric value, when `value_kind` selects it
    ValueNumber,
    /// String value, when `value_kind` selects it
    ValueString,
    /// Geometry value, when `value_kind` selects it
    ValueGeometry,
    /// JSON object or array value, when `value_kind` selects it
    ValueObject,
    /// URI value, when `value_kind` selects it
    ValueUri,
    /// String value too long for `value_string`'s B-tree, when `value_kind`
    /// selects String
    ValueLongText,
    /// URI value too long for `value_uri`'s B-tree, when `value_kind` selects
    /// URI
    ValueLongUri,
}

/// Alias `e` for the entities table.
///
/// Shared by the context type predicate and the temporal stage-1 statement,
/// which both read the entities row under this alias.
#[derive(Iden, Clone, Copy)]
#[iden = "e"]
pub struct E;

